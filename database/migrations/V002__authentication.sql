CREATE TABLE public.auth_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username character varying(64) NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role character varying(32) NOT NULL DEFAULT 'admin',
  must_change_password boolean NOT NULL DEFAULT true,
  active boolean NOT NULL DEFAULT true,
  failed_login_attempts integer NOT NULL DEFAULT 0,
  locked_until timestamp with time zone,
  password_changed_at timestamp with time zone,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT auth_users_username_normalized CHECK (username = lower(username)),
  CONSTRAINT auth_users_role_check CHECK (role IN ('admin')),
  CONSTRAINT auth_users_failed_login_attempts_check CHECK (failed_login_attempts >= 0)
);

CREATE TABLE public.auth_sessions (
  token_hash character(64) PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.auth_users(id) ON DELETE CASCADE,
  csrf_token_hash character(64) NOT NULL,
  expires_at timestamp with time zone NOT NULL,
  revoked_at timestamp with time zone,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  last_seen_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX auth_sessions_user_id_idx ON public.auth_sessions (user_id);
CREATE INDEX auth_sessions_expires_at_idx ON public.auth_sessions (expires_at);
